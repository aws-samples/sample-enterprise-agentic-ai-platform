#!/usr/bin/env bash
# 04 — Generate a RESOLVED enterprise.testbed.tfvars from the VPC + IAM fixture outputs.
# Leaves the committed configs/enterprise.tfvars preset untouched (it documents
# the base posture + overrides); writes a filled, throwaway copy the apply uses.
#
# NOTE: this test bed deliberately sets deploy_langfuse=true to EXERCISE the
# private in-VPC observability path end to end. The enterprise PRESET defaults
# Langfuse OFF (ADR-036); the bed overrides it ON to validate that path.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
VPC_DIR="$HERE/enterprise-vpc"
IAM_DIR="$HERE/iam-roles"
OUT="$REPO/platform/eap-platform/configs/enterprise.testbed.tfvars"

echo "=== 04 — generate $OUT ==="

VPC_ID=$(cd "$VPC_DIR" && terraform output -raw vpc_id)
# private subnet id list -> HCL list
PRIV_JSON=$(cd "$VPC_DIR" && terraform output -json private_subnet_ids)

GATEWAY_ARN=$(cd "$IAM_DIR" && terraform output -raw gateway_role_arn)
RUNTIME_ARN=$(cd "$IAM_DIR" && terraform output -raw studio_runtime_role_arn)
READ_ARN=$(cd "$IAM_DIR" && terraform output -raw studio_read_role_arn)
COMMIT_ARN=$(cd "$IAM_DIR" && terraform output -raw commit_validation_role_arn)
OBS_ARN=$(cd "$IAM_DIR" && terraform output -raw observability_role_arn)

cat > "$OUT" <<EOF
# GENERATED by test/enterprise-testbed/scripts/04-gen-tfvars.sh — do not edit by hand.
# Resolved ENTERPRISE preset for the test bed: enterprise VPC imported, 5
# standalone roles externalized (hardened), pipeline roles platform-created.
# Langfuse ON here to exercise the observability path (preset default is OFF).

deploy_console     = false
agent_network_mode = "VPC"

vpc_id             = "$VPC_ID"
private_subnet_ids = $PRIV_JSON
public_subnet_ids  = $PRIV_JSON  # internal ALB — private subnets are correct

deploy_langfuse           = true
oidc_discovery_url        = ""
enable_transaction_search = false

# Externalized standalone roles (hardened) — from the iam-roles fixture.
gateway_role_arn           = "$GATEWAY_ARN"
studio_runtime_role_arn    = "$RUNTIME_ARN"
studio_read_role_arn       = "$READ_ARN"
commit_validation_role_arn = "$COMMIT_ARN"
observability_role_arn     = "$OBS_ARN"
# (10 pipeline *_role_arn left empty => platform-created)
EOF

echo "Wrote:"
echo "  $OUT"
echo ""
cat "$OUT"
